def rich(text, root):
    """Escape text, then turn [label](@/path) into an internal link."""
    return re.sub(r"\[([^\]]+)\]\(@/([^)]+)\)", lambda m: '<a href="%s%s">%s</a>' % (root, m.group(2), m.group(1)), esc(text))

def legal_sections(l, root):
    toc, out = [], []
    for sec in l.get("sections", []):
        sid = sec.get("id") or re.sub(r"[^a-z0-9]+", "-", re.sub(r"^\d+\.\s*", "", sec["h"]).lower()).strip("-")
        toc.append('<li><a href="#%s">%s</a></li>' % (sid, esc(sec["h"])))
        body = "".join("<p>%s</p>" % rich(t, root) for t in sec.get("p", []))
        if sec.get("ul"):
            body += "<ul>%s</ul>" % "".join("<li>%s</li>" % rich(t, root) for t in sec["ul"])
        if sec.get("table"):
            t = sec["table"]
            body += ('<div class="table-wrap"><table class="legal-table"><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>'
                     % ("".join("<th scope=\"col\">%s</th>" % esc(h) for h in t["head"]),
                        "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % esc(c) for c in r) for r in t["rows"])))
        body += "".join("<p>%s</p>" % rich(t, root) for t in sec.get("after", []))
        if sid == "cookies":
            body += '<p><button type="button" class="chip chip-primary" data-cookie-settings>Open cookie settings</button></p>'
        out.append('<section class="legal-sec" id="%s"><h2>%s</h2>%s</section>' % (sid, esc(sec["h"]), body))
    nav = ('<nav class="legal-toc" aria-label="On this page"><strong>On this page</strong><ul>%s</ul></nav>' % "".join(toc)) if len(toc) >= 8 else ""
    return nav, "".join(out)

