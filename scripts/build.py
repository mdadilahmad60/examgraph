def schema_tags(p, canonical):
    """JSON-LD: WebApplication for every tool page, plus FAQPage when the page has FAQs (same text as shown on the page)."""
    def tag(obj):
        return '  <script type="application/ld+json">%s</script>\n' % json.dumps(obj, ensure_ascii=False).replace("</", "<\\/")
    feats = [re.sub(r"<[^>]+>", "", x if isinstance(x, str) else " ".join(map(str, x))).strip() for x in (p.get("points") or [])][:6]
    app = {
        "@context": "https://schema.org",
        "@type": "WebApplication",
        "@id": canonical + "#app",
        "name": p["title"].split("|")[0].strip(),
        "description": p["desc"],
        "url": canonical,
        "mainEntityOfPage": canonical,
        "applicationCategory": "EducationalApplication",
        "applicationSubCategory": p.get("category_name", "Graphing calculator"),
        "operatingSystem": "Any (web browser)",
        "browserRequirements": "Requires JavaScript",
        "inLanguage": "en-US",
        "isAccessibleForFree": True,
        "image": og_url(p.get("category")),
        "dateModified": lastmod(p["path"], p),
        "audience": {"@type": "EducationalAudience", "educationalRole": "student"},
        "publisher": {"@id": SITE["domain"] + "/#org"},
        "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
    }
    if feats:
        app["featureList"] = feats
    out = tag(app)
    items = p.get("faq")
    if items:
        out += tag({
            "@context": "https://schema.org",
            "@type": "FAQPage",
            "mainEntity": [
                {"@type": "Question", "name": i["q"], "acceptedAnswer": {"@type": "Answer", "text": i["a"]}}
                for i in items
            ],
        })
    return out

