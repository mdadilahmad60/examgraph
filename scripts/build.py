def related_paths(p):
    """3-5 same-category pages that are topically closest to p."""
    slug = p["path"].split("/", 1)[1]
    cat = [q["path"] for q in DATA["pages"] if q["category"] == p["category"] and q["path"] != p["path"]]
    def match(prefix, path):
        return path.split("/", 1)[1].startswith(prefix)
    out = []
    for g in RELATED_GROUPS:
        if any(slug.startswith(m) for m in g):
            for m in g:
                for path in cat:
                    if match(m, path) and path not in out:
                        out.append(path)
    for path in cat:
        if len(out) >= 3:
            break
        if path not in out:
            out.append(path)
    return out[:5]

def related_text(p):
    """One sentence of contextual internal links inside the page copy (links go to same-category tools)."""
    paths = related_paths(p)
    if len(paths) < 3:
        return ""
    root = depth_prefix(p["path"])
    links = ['<a href="%s%s">%s</a>' % (root, path, esc(PAGE_BY_PATH[path]["h1"])) for path in paths]
    joined = ", ".join(links[:-1]) + " and " + links[-1]
    lead = RELATED_LEADS[sum(map(ord, p["path"])) % len(RELATED_LEADS)]
    return '<p class="related-inline">%s</p>' % (lead % joined)

