def lastmod(key, obj):
    """Real last-modified date: only moves when the page's source content changes (hash stored in scripts/lastmod.json)."""
    h = hashlib.sha1(json.dumps(obj, sort_keys=True, ensure_ascii=False).encode("utf8")).hexdigest()[:12]
    cur = LASTMOD.get(key)
    if not cur or cur["hash"] != h:
        cur = LASTMOD[key] = {"hash": h, "date": TODAY}
    return cur["date"]

