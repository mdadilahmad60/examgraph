def nav_links(n, root, current=None, limit=6):
    lis = []
    for path in n["top"][:limit]:
        p = PAGE_BY_PATH[path]
        cur = ' aria-current="page"' if path == current else ""
        lis.append('<li><a href="%s%s"%s>%s</a></li>' % (root, path, cur, esc(p["h1"])))
    lis.append('<li class="nav-all"><a href="%s%s">View all %d tools &rarr;</a></li>' % (root, n["hub"], len(cat_pages(n["id"]))))
    return "".join(lis)

